import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from beer_audit.audit import sha256, write_json


def compare_csv(actual, expected, ignore_timing=False):
    import pandas as pd
    frames = [pd.read_csv(p, float_precision='round_trip') for p in (actual, expected)]
    for frame in frames:
        if ignore_timing and 'seconds' in frame:
            frame.drop(columns='seconds', inplace=True)
        for column in frame:
            if pd.api.types.is_string_dtype(frame[column].dtype):
                frame[column] = frame[column].map(
                    lambda v: v.replace('\r\n', '\n') if isinstance(v, str) else v)
    pd.testing.assert_frame_equal(*frames, check_dtype=False, check_exact=False, atol=1e-10, rtol=1e-10)


def compare_npz(actual, expected):
    import numpy as np
    # These are arrays generated by this repository, never external pickled models.
    with np.load(actual, allow_pickle=True) as a, np.load(expected, allow_pickle=True) as b:
        assert set(a.files) == set(b.files), 'NPZ keys differ'
        for key in a.files:
            assert a[key].shape == b[key].shape, key
            if a[key].dtype.kind in 'biufc' and b[key].dtype.kind in 'biufc':
                np.testing.assert_allclose(a[key], b[key], atol=1e-10, rtol=1e-10, equal_nan=True, err_msg=key)
            else:
                np.testing.assert_array_equal(a[key], b[key], err_msg=key)


def locked_packages():
    result = {}
    for lock in ('requirements-lock.txt', 'requirements-r3-lock.txt'):
        for line in (ROOT / lock).read_text(encoding='utf-8').splitlines():
            line = line.strip()
            if not line or line.startswith(('#', '-r ')):
                continue
            name, expected = line.split('==')
            actual = importlib.metadata.version(name)
            if actual != expected:
                raise RuntimeError(f'{name}: installed {actual}; lock requires {expected}')
            result[name] = actual
    return result


def run(args):
    source, output = args.source.resolve(), args.output.resolve()
    statement = (args.statement or source.parent / '2026年MathorCup大数据挑战赛-赛道A初赛.pdf').resolve()
    if not args.resume:
        output.mkdir(parents=True, exist_ok=False)
        (output / 'logs').mkdir()
    env = dict(os.environ, PYTHONPATH=str(ROOT / 'src'), PYTHONIOENCODING='utf-8',
               MPLCONFIGDIR=str(output / 'matplotlib_cache'))
    report = dict(status='running', started_utc=datetime.now(timezone.utc).isoformat(),
                  git_commit=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
                  working_tree_dirty=bool(subprocess.check_output(
                      ['git', 'status', '--porcelain', '--untracked-files=no'], cwd=ROOT, text=True).strip()),
                  python=platform.python_version(), executable=sys.executable, system=platform.platform(),
                  initial_model_files=[str(p.relative_to(ROOT)) for p in ROOT.rglob('*.joblib')
                                       if '.venv' not in p.parts and 'checkpoints' not in p.parts],
                  steps=[], comparisons=[], source=str(source),
                  rebuilt=['source/scope/raw-label audits', 'R2 and R2b Q1 training and real prediction CLI',
                           'R3 raw-scale explanations', 'task4 generation and complete historical candidate checks',
                           'task5 repeated nested validation including independent model refits',
                           'standardized Q2 assembly and literature ledger assembly'],
                  versioned_reuse=['Q2 200-refit selections and 1999-permutation nulls; independently checked, not rerun',
                                  'historical Q2 forest comparisons and curated literature ledger',
                                  'historical Q1 threshold-proxy evidence used only by historical Q2 assembly',
                                  'historical 8293 eligible path points and original 11 paths, not a new nested search',
                                  'versioned feature/label definitions rechecked before training'],
                  comparison_exclusions={'seconds': 'elapsed runtime is not a scientific result',
                     'R2b fit_log.csv': 'historical 25-row log includes superseded full-forest seed; new run has 24 valid fits',
                     'binary/plot metadata': 'compare numerical arrays/tables, not joblib, ZIP timestamps or rendering bytes'},
                  interpretation='Numerical reproduction on the same 250 development beers; not external validation or a brewing intervention.')
    if args.resume:
        previous = json.loads((output/'reproduction.json').read_text(encoding='utf-8'))
        if previous['status'] != 'failed' or previous['source'] != str(source):
            raise ValueError('Resume requires a failed run with the same source directory')
        # Successful model stages remain usable only while their implementation is unchanged.
        # The runner and reader-view packaging may be repaired without retraining models.
        presentation = {'scripts/reproduce_final.py', 'scripts/build_paper_takeout.py'}
        for name, expected in previous['code_sha256'].items():
            if name.replace('\\', '/') not in presentation and sha256(ROOT/name) != expected:
                raise ValueError('Completed-stage code changed; start a new run: '+name)
        previous.setdefault('recovery', []).append(dict(
            prior_error=previous.pop('error'), resumed_utc=datetime.now(timezone.utc).isoformat(),
            git_commit=report['git_commit'], working_tree_dirty=report['working_tree_dirty'],
            presentation_code_sha256={name:sha256(ROOT/name) for name in presentation}))
        report = previous
        report['status'] = 'running'
    successful = {s['name']:s for s in report['steps'] if s['exit_code'] == 0}
    def save():
        write_json(output / 'reproduction.json', report)
    def step(name, *arguments):
        command = [sys.executable, *map(str, arguments)]
        if name in successful:
            if successful[name]['command'] != command:
                raise ValueError('Resume command differs: '+name)
            print('Retained successful step '+name, flush=True)
            return
        start = time.perf_counter()
        log = output / 'logs' / (name + '.log')
        print('Starting ' + name, flush=True)
        with log.open('w', encoding='utf-8') as stream:
            result = subprocess.run(command, cwd=ROOT, env=env, stdout=stream, stderr=subprocess.STDOUT)
        report['steps'].append(dict(name=name, command=command, exit_code=result.returncode,
                                   seconds=round(time.perf_counter()-start, 3), log=str(log.relative_to(output))))
        save()
        if result.returncode:
            print(log.read_text(encoding='utf-8')[-5000:], flush=True)
            raise RuntimeError('Failed step: ' + name)
        print('Completed ' + name, flush=True)
    def compare_dir(actual, historical, names=None):
        frozen = ROOT / 'outputs' / historical
        names = names or sorted(p.name for p in frozen.iterdir()
                                if p.name.endswith(('.csv', '.csv.gz', '.npz')))
        for name in names:
            if historical == 'r2b_tail_risk_20261026' and name == 'fit_log.csv':
                continue
            a, b = actual / name, frozen / name
            if name.endswith('.npz'):
                compare_npz(a, b)
            else:
                compare_csv(a, b, ignore_timing=name in ('fit_log.csv', 'model_fit_log.csv'))
            report['comparisons'] = [r for r in report['comparisons'] if r['rebuilt'] != str(a.relative_to(output))]
            report['comparisons'].append(dict(rebuilt=str(a.relative_to(output)),
                reference=str(b.relative_to(ROOT)), status='passed', rebuilt_sha256=sha256(a), reference_sha256=sha256(b)))
        save()
    save()
    try:
        if sys.version_info[:2] != (3, 12):
            raise RuntimeError('Use Python 3.12 with requirements-r3-lock.txt')
        report['packages'] = locked_packages()
        report['code_sha256'] = {str(p.relative_to(ROOT)): sha256(p) for folder in ('src', 'scripts', 'configs')
                                for p in (ROOT/folder).rglob('*') if p.suffix in ('.py', '.json')}
        step('dependency_check', '-m', 'pip', 'check')
        step('tests', '-m', 'unittest', 'discover', '-s', 'tests', '-q')
        reference = args.reference.resolve() if args.reference else ROOT/'data/reference/zenodo10653704/Supplemental Files and Figure source files.xlsx'
        raw = args.raw.resolve() if args.raw else ROOT/'data/reference/zenodo23624915/Raw sensory data anonymized.csv'
        if not args.reference:
            step('fetch_public_workbook', 'scripts/fetch_reference.py')
        if not args.raw:
            step('fetch_public_raw', 'scripts/fetch_raw_sensory.py')
        manifest = json.loads((ROOT/'data/reference/zenodo10653704/download_manifest.json').read_text(encoding='utf-8'))
        workbook_hash = next(r['sha256'] for r in manifest if r['file'] == reference.name)
        raw_hash = json.loads((ROOT/'data/reference/zenodo23624915/download_manifest.json').read_text(encoding='utf-8'))['sha256']
        for name, path, expected in [('reference', reference, workbook_hash), ('raw', raw, raw_hash)]:
            if sha256(path) != expected:
                raise ValueError('Pinned source hash differs: ' + name)
            report[name] = dict(path=str(path), sha256=expected, supplied_offline=bool(getattr(args, name)))
        audit, scope, labels = (output/p for p in ('audit', 'scope', 'raw_sensory'))
        step('source_audit', '-m', 'beer_audit', '--source', source, '--output', audit)
        step('scope_audit', 'scripts/audit_task1_scope.py', '--source', source, '--statement', statement, '--output', scope)
        compare_dir(audit, 'p0_audit_20261023_final', ['feature_dictionary.csv', 'sensory_mapping.csv', 'correlation_method_comparison.csv'])
        compare_dir(scope, 'task1_acceptance_20261025', ['scorecard_scope.csv', 'defect_scope.csv'])
        step('raw_label_audit', 'scripts/audit_raw_sensory.py', '--source', source, '--raw', raw, '--output', labels)
        compare_dir(labels, 'raw_sensory_audit_20261025')
        common = ['--source', source, '--raw', raw]
        r2, q1 = output/'r2', output/'q1'
        for name, script, folder in [('r2', 'r2_raw_q1', r2), ('q1', 'r2b_tail_risk', q1)]:
            step(name+'_training', 'scripts/'+script+'.py', *common, '--output', folder)
            smoke = output/(name+'_cli')
            step(name+'_prediction_cli', 'scripts/predict_q1.py', '--model', folder/'model.joblib',
                 '--input', source/'1.csv', '--output', smoke)
            extra = ['--r2-output', r2] if name == 'q1' else []
            step(name+'_verification', 'scripts/verify_'+script+'.py', *common, '--output', folder, '--smoke', smoke, *extra)
            compare_dir(folder, 'r2_raw_q1_20261026' if name == 'r2' else 'r2b_tail_risk_20261026')
        q2std = output/'q2_standardized'
        q2args = ['--source', source, '--audit', audit, '--reference', reference, '--output', q2std]
        step('q2_standardized_assembly', 'scripts/complete_q2_task4.py', *q2args)
        step('q2_standardized_verification', 'scripts/verify_q2_task4.py', *q2args)
        compare_dir(q2std, 'q2_task4_20261025')
        step('q2_literature_assembly', 'scripts/task3_q2_literature.py', '--output', output/'q2_literature')
        compare_dir(output/'q2_literature', 'task3_q2_literature_20261025')
        q2 = output/'q2_raw'
        step('q2_raw_training', 'scripts/r3_raw_explanation.py', *common, '--output', q2)
        step('q2_raw_verification', 'scripts/verify_r3_raw_explanation.py', *common, '--output', q2)
        compare_dir(q2, 'r3_raw_explanation_20261026')
        q3 = output/'q3'
        q3args = [*common, '--q1', q1, '--output', q3]
        step('q3_training_and_checks', 'scripts/task4_raw_q3.py', *q3args)
        step('q3_verification', 'scripts/verify_task4_raw_q3.py', *q3args, '--cache', output/'q3_verification_cache')
        compare_dir(q3, 'task4_raw_q3_20261026')
        validation = output/'validation'
        step('repeated_nested_training', 'scripts/task5_repeated_nested.py', *common, '--output', validation)
        step('repeated_nested_verification', 'scripts/verify_task5_repeated_nested.py', *common, '--output', validation)
        compare_dir(validation, 'task5_repeated_nested_20261026')
        report['checks'] = {name: json.loads((output/name/'verification.json').read_text(encoding='utf-8'))
                            for name in ('raw_sensory', 'r2', 'q1', 'q2_standardized', 'q2_literature', 'q2_raw', 'q3', 'validation')}
        assert all(v['status'] == 'passed' for v in report['checks'].values())
        step('paper_data_bundle', 'scripts/build_paper_takeout.py', '--run', output, '--output', output/'paper')
        report['rebuilt_model_files'] = [str(p.relative_to(output)) for p in output.rglob('*.joblib')]
        report['status'] = 'passed'
        report['finished_utc'] = datetime.now(timezone.utc).isoformat()
        save()
        print(f'Final workflow passed: {len(report["steps"])} steps; {len(report["comparisons"])} numerical file comparisons.', flush=True)
    except BaseException as error:
        report.update(status='failed', error=f'{type(error).__name__}: {error}', finished_utc=datetime.now(timezone.utc).isoformat())
        save()
        raise


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True, help='New directory; existing results are never overwritten')
    p.add_argument('--statement', type=Path)
    p.add_argument('--reference', type=Path, help='Offline copy of the pinned public workbook')
    p.add_argument('--raw', type=Path, help='Offline copy of the pinned anonymized scores')
    p.add_argument('--resume', action='store_true', help='Continue a failed run; successful stages require unchanged scientific code and commands')
    run(p.parse_args())
